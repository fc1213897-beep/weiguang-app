function buildKaoyanItems(): RankedItem[] {
  return KAOYAN_WORDS.map((word, index) => {
    const rank = index + 1;
    return {
      id: `w-${rank}`,
      rank,
      tier: tierForRank(rank, KAOYAN_WORDS.length),
      label: word,
    };
  });
}

const kaoyanTop3000Provider: DataSourceProvider = {
  id: "kaoyan_top3000",
  label: "考研高频词汇（示例集）",
  load: async () => buildKaoyanItems(),
};

const providers = new Map<string, DataSourceProvider>([
  [kaoyanTop3000Provider.id, kaoyanTop3000Provider],
]);

export function getDataSourceProvider(
  id: string
): DataSourceProvider | undefined {
  return providers.get(id);
}

export async function loadDataSourceItems(
  id: string
): Promise<RankedItem[]> {
  const provider = providers.get(id);
  if (!provider) return [];
  return provider.load();
}

export function listDataSources(): DataSourceProvider[] {
  return Array.from(providers.values());
}

export function registerDataSource(provider: DataSourceProvider): void {
  providers.set(provider.id, provider);
}
