function tierForRank(rank: number, total: number): ItemTier {
  const highCut = Math.ceil(total * 0.33);
  const midCut = Math.ceil(total * 0.66);
  if (rank <= highCut) return "high";
  if (rank <= midCut) return "mid";
  return "low";
}

